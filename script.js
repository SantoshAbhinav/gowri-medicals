function renderFiles() {
  const container = $("selectedFiles");
  container.replaceChildren();
  container.hidden = chosenFiles.length === 0;
  chosenFiles.forEach((file, index) => {
    const row = document.createElement("div");
    row.className = "selected-file";
    const icon = document.createElement("span");
    icon.textContent = file.type === "application/pdf" ? "PDF" : "▧";
    const label = document.createElement("span");
    label.textContent = `${file.name} · ${(file.size / 1024 / 1024).toFixed(2)} MB`;
    const remove = document.createElement("button");
    remove.type = "button";
    remove.textContent = "×";
    remove.setAttribute("aria-label", `Remove ${file.name}`);
    remove.addEventListener("click", () => {
      chosenFiles.splice(index, 1);
      renderFiles();
      setStatus(copy[lang].fileRemoved);
    });
    row.append(icon, label, remove);
    container.append(row);
  });
}
$("prescription").addEventListener("change", event => {
  const incoming = Array.from(event.target.files || []);
  const allowed = ["image/jpeg", "image/png", "application/pdf"];
  if (chosenFiles.length + incoming.length > SHOP.maxFiles) {
    setStatus(copy[lang].errCount, true);
    event.target.value = "";
    return;
  }
  if (incoming.some(file => !allowed.includes(file.type))) {
    setStatus(copy[lang].errType, true);
    event.target.value = "";
    return;
  }
  if (incoming.some(file => file.size > SHOP.maxFileBytes)) {
    setStatus(copy[lang].errSize, true);
    event.target.value = "";
    return;
  }
  const combined = [...chosenFiles, ...incoming].reduce((sum, file) => sum + file.size, 0);
  if (combined > 20 * 1024 * 1024) {
    setStatus(copy[lang].errTotal, true);
    event.target.value = "";
    return;
  }
  chosenFiles = [...chosenFiles, ...incoming];
  renderFiles();
  event.target.value = "";
  setStatus("");
});

function validIndianMobile(raw) {
  let digits = raw.replace(/\D/g, "");
  if (digits.startsWith("91") && digits.length === 12) digits = digits.slice(2);
  return /^[6-9]\d{9}$/.test(digits);
}
